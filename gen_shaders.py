#!/usr/bin/env python3
"""Makes shaders.h: the SPIR-V of probe.comp's 9 variants (workgroups 64x1, 8x8, 16x4; plain, image, texture).
Needs glslc (shaderc) on the PATH. Run it in this folder: python3 gen_shaders.py"""
import pathlib
import struct
import subprocess

out = ["// generated by build: SPIR-V of probe.comp variants", "#include <cstdint>",
       "struct ProbeShader { const char* name; uint32_t lx, ly, mode; const uint32_t* code; uint32_t words; };"]
names = []
for lx, ly in ((64, 1), (8, 8), (16, 4)):
    for mode, mname in ((0, "plain"), (1, "image"), (2, "texture")):
        n = f"cs_{lx}x{ly}_{mname}"
        spv = pathlib.Path(f"{n}.spv")
        subprocess.run(["glslc", "--target-env=vulkan1.3", f"-DLX={lx}", f"-DLY={ly}", f"-DMODE={mode}",
                        "-fshader-stage=compute", "probe.comp", "-o", str(spv)], check=True)
        words = struct.unpack(f"<{spv.stat().st_size // 4}I", spv.read_bytes())
        out.append(f"static const uint32_t {n}[] = {{" + ",".join(f"0x{w:08x}u" for w in words) + "};")
        names.append((n, lx, ly, mode))
        spv.unlink()
out.append("static const ProbeShader kShaders[] = {" +
           ",".join(f'{{"{n}",{lx},{ly},{m},{n},0+sizeof({n})/4}}' for n, lx, ly, m in names) + "};")
pathlib.Path("shaders.h").write_text("\n".join(out) + "\n")
print(len(names), "variants")
